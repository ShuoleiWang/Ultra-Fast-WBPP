const MESSAGES: Record<UiLanguage, Record<MessageKey, string>> = { en: EN, "zh-CN": ZH };
const STORAGE_KEY = "ultra-fast-wbpp.language";

export type Translator = (key: MessageKey, values?: Record<string, string | number>) => string;

export function translateCurrent(key: MessageKey): string {
  const language: UiLanguage = typeof document !== "undefined" && document.documentElement.lang === "zh-CN" ? "zh-CN" : "en";
  return MESSAGES[language][key];
}

function storedLanguage(): UiLanguage {
  if (typeof window === "undefined") return "en";
  try {
    return window.localStorage.getItem(STORAGE_KEY) === "zh-CN" ? "zh-CN" : "en";
  } catch {
    return "en";
  }
}

export function useI18n() {
  const [language, setLanguage] = useState<UiLanguage>(storedLanguage);
  useEffect(() => {
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Storage can be unavailable in hardened/private webviews. Language is a
      // convenience preference and must never prevent the scientific UI boot.
    }
    document.documentElement.lang = language;
  }, [language]);
  const t = useCallback<Translator>((key, values = {}) => {
    let message: string = MESSAGES[language][key];
    for (const [name, value] of Object.entries(values)) {
      message = message.replaceAll(`{${name}}`, String(value));
    }
    return message;
  }, [language]);
  return { language, setLanguage, t };
}
